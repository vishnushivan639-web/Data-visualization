import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df=pd.read_csv("/content/sample_data/kc_house_data.csv")

df

df.head()

df.tail()

df.info()

df.columns

df.describe()

df.shape

df.isnull().sum()

df.duplicated().sum()

df['date'] = pd.to_datetime(df["date"].astype(str).str[:8], format="%Y%m%d",errors="coerce")

df["date"].head()

df['sale_year'] = df['date'].dt.year

df['sale_year'].head()

import datetime

currentyear= datetime.datetime.now().year

df["property_Age"] =currentyear-df["yr_built"]

df["property_Age"].head()

df['years_since_renovation'] = np.where(
    df['yr_renovated'] > 0,
    df['sale_year'] - df['yr_renovated'],
    np.nan
)

df['is_renovated'] = (df['yr_renovated'] > 0).astype(int)
print(df[['date', 'sale_year', 'property_Age',
          'is_renovated', 'years_since_renovation']].head())

df['price_per_sqft_living'] = (
    df['price'] / df['sqft_living'].replace(0, np.nan)
)
df['price_per_sqft_lot'] = (
    df['price'] / df['sqft_lot'].replace(0, np.nan)
)
print(df[['price', 'sqft_living', 'sqft_lot',
          'price_per_sqft_living',
          'price_per_sqft_lot']].head())

Q1 = df['price_per_sqft_living'].quantile(0.25)
Q3 = df['price_per_sqft_living'].quantile(0.75)

IQR = Q3 - Q1

lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

outliers_living = df[
    (df['price_per_sqft_living'] < lower_bound) |
    (df['price_per_sqft_living'] > upper_bound)
]

print("Living Area Price per Square Foot")
print("Q1:", Q1)
print("Q3:", Q3)
print("IQR:", IQR)
print("Lower Bound:", lower_bound)
print("Upper Bound:", upper_bound)
print("Number of Outliers:", len(outliers_living))

Q1_lot = df['price_per_sqft_lot'].quantile(0.25)
Q3_lot = df['price_per_sqft_lot'].quantile(0.75)

IQR_lot = Q3_lot - Q1_lot

lower_bound_lot = Q1_lot - 1.5 * IQR_lot
upper_bound_lot = Q3_lot + 1.5 * IQR_lot

outliers_lot = df[
    (df['price_per_sqft_lot'] < lower_bound_lot) |
    (df['price_per_sqft_lot'] > upper_bound_lot)
]

print("\nLot Size Price per Square Foot")
print("Q1:", Q1_lot)
print("Q3:", Q3_lot)
print("IQR:", IQR_lot)
print("Lower Bound:", lower_bound_lot)
print("Upper Bound:", upper_bound_lot)
print("Number of Outliers:", len(outliers_lot))

plt.figure(figsize=(8, 4))
sns.boxplot(x=df['price_per_sqft_living'])
plt.title('Box Plot - Price per Square Foot (Living Area)')
plt.xlabel('Price per Square Foot')
plt.show()

plt.figure(figsize=(8, 4))
sns.boxplot(x=df['price_per_sqft_lot'])
plt.title('Box Plot - Price per Square Foot (Lot Size)')
plt.xlabel('Price per Square Foot')
plt.show()